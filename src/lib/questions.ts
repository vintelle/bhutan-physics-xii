import { z } from "zod";

/** The seven item types required by the platform. */
export const QUESTION_TYPES = [
  "MCQ",
  "TRUE_FALSE",
  "FILL_BLANK",
  "MATCHING",
  "NUMERICAL",
  "ASSERTION_REASON",
  "CONCEPTUAL",
] as const;
export type QuestionType = (typeof QUESTION_TYPES)[number];

export const TYPE_LABEL: Record<QuestionType, string> = {
  MCQ: "Multiple choice",
  TRUE_FALSE: "True / False",
  FILL_BLANK: "Fill in the blanks",
  MATCHING: "Matching",
  NUMERICAL: "Numerical problem",
  ASSERTION_REASON: "Assertion & Reason",
  CONCEPTUAL: "Conceptual (written)",
};

/** Bloom's levels the quiz engine targets (Creating is assessed through performance tasks). */
export const QUIZ_BLOOMS = ["REMEMBERING", "UNDERSTANDING", "APPLYING", "ANALYSING", "EVALUATING"] as const;
export const ALL_BLOOMS = [...QUIZ_BLOOMS, "CREATING"] as const;
export type Bloom = (typeof ALL_BLOOMS)[number];
export const BLOOM_LABEL: Record<Bloom, string> = {
  REMEMBERING: "Remembering",
  UNDERSTANDING: "Understanding",
  APPLYING: "Applying",
  ANALYSING: "Analysing",
  EVALUATING: "Evaluating",
  CREATING: "Creating",
};

export const DOMAIN_LABEL = {
  SK: "Scientific Knowledge",
  WS: "Working Scientifically",
  SV: "Scientific Values and Attitudes",
} as const;

/** Standard Assertion-Reason key used in Bhutanese/BCSEA-style papers. */
export const AR_OPTIONS = [
  "Both A and R are true, and R is the correct explanation of A.",
  "Both A and R are true, but R is not the correct explanation of A.",
  "A is true, but R is false.",
  "A is false, but R is true.",
  "Both A and R are false.",
];

// ---------- payload + answer schemas per type ----------
export const payloadSchemas = {
  MCQ: z.object({ options: z.array(z.string().min(1)).min(3).max(6) }),
  TRUE_FALSE: z.object({}).passthrough(),
  FILL_BLANK: z.object({}).passthrough(), // blanks are marked "____" in the stem
  MATCHING: z.object({ left: z.array(z.string().min(1)).min(3).max(6), right: z.array(z.string().min(1)).min(3).max(6) }),
  NUMERICAL: z.object({ unit: z.string() }),
  ASSERTION_REASON: z.object({ assertion: z.string().min(1), reason: z.string().min(1) }),
  CONCEPTUAL: z.object({ keyPoints: z.array(z.string().min(1)).min(2).max(6) }),
} satisfies Record<QuestionType, z.ZodTypeAny>;

export const answerSchemas = {
  MCQ: z.object({ index: z.number().int().min(0) }),
  TRUE_FALSE: z.object({ value: z.boolean() }),
  FILL_BLANK: z.object({ blanks: z.array(z.array(z.string().min(1)).min(1)).min(1) }),
  MATCHING: z.object({ pairs: z.array(z.number().int().min(0)) }), // pairs[i] = index in right[] for left[i]
  NUMERICAL: z.object({ value: z.number(), tolerancePct: z.number().min(0).max(20).default(2) }),
  ASSERTION_REASON: z.object({ index: z.number().int().min(0).max(4) }),
  CONCEPTUAL: z.object({ modelAnswer: z.string().min(1) }),
} satisfies Record<QuestionType, z.ZodTypeAny>;

export const responseSchemas = {
  MCQ: z.object({ index: z.number().int() }),
  TRUE_FALSE: z.object({ value: z.boolean() }),
  FILL_BLANK: z.object({ blanks: z.array(z.string()) }),
  MATCHING: z.object({ pairs: z.array(z.number().int()) }),
  NUMERICAL: z.object({ value: z.union([z.number(), z.string()]) }),
  ASSERTION_REASON: z.object({ index: z.number().int() }),
  CONCEPTUAL: z.object({ text: z.string().max(4000) }),
} satisfies Record<QuestionType, z.ZodTypeAny>;

/** Full item as authored by a teacher, uploaded, seeded, or generated by AI. */
export const questionInputSchema = z
  .object({
    type: z.enum(QUESTION_TYPES),
    bloom: z.enum(ALL_BLOOMS),
    domain: z.enum(["SK", "WS", "SV"]).default("SK"),
    difficulty: z.number().int().min(1).max(3).default(2),
    marks: z.number().int().min(1).max(10).default(1),
    outcomeCode: z.string().regex(/^XII\.(NM|FMT|EM|WO|ANSP)\.\d{2}$/),
    subtopicNumber: z.string().regex(/^\d\.\d\.\d$/).optional().nullable(),
    stem: z.string().min(5),
    payload: z.record(z.string(), z.unknown()).default({}),
    answer: z.record(z.string(), z.unknown()),
    explanation: z.string().min(10),
    misconception: z.string().min(5),
    hints: z.array(z.string().min(3)).length(3),
    solutionSteps: z.array(z.string()).default([]),
    scopeNote: z.string().optional().nullable(),
  })
  .superRefine((q, ctx) => {
    const p = payloadSchemas[q.type].safeParse(q.payload);
    if (!p.success) ctx.addIssue({ code: "custom", path: ["payload"], message: `Invalid ${q.type} payload: ${p.error.issues[0]?.message}` });
    const a = answerSchemas[q.type].safeParse(q.answer);
    if (!a.success) {
      ctx.addIssue({ code: "custom", path: ["answer"], message: `Invalid ${q.type} answer: ${a.error.issues[0]?.message}` });
      return;
    }
    if (q.type === "MCQ" && p.success) {
      const n = (q.payload as { options: string[] }).options.length;
      if ((q.answer as { index: number }).index >= n) ctx.addIssue({ code: "custom", path: ["answer"], message: "MCQ answer index out of range" });
    }
    if (q.type === "FILL_BLANK") {
      const blanks = (q.stem.match(/_{3,}/g) ?? []).length;
      if (blanks !== (q.answer as { blanks: unknown[] }).blanks.length)
        ctx.addIssue({ code: "custom", path: ["answer"], message: `Stem has ${blanks} blank(s) (____) but answer has ${(q.answer as { blanks: unknown[] }).blanks.length}` });
    }
    if (q.type === "MATCHING" && p.success) {
      const { left, right } = q.payload as { left: string[]; right: string[] };
      const pairs = (q.answer as { pairs: number[] }).pairs;
      if (pairs.length !== left.length || pairs.some((i) => i >= right.length) || new Set(pairs).size !== pairs.length)
        ctx.addIssue({ code: "custom", path: ["answer"], message: "Matching pairs must map each left item to a distinct right item" });
    }
    if (q.type === "NUMERICAL" && q.solutionSteps.length === 0)
      ctx.addIssue({ code: "custom", path: ["solutionSteps"], message: "Numerical problems need step-by-step solution steps" });
  });
export type QuestionInput = z.infer<typeof questionInputSchema>;

/** What a student is allowed to see before answering (no answer, no explanation, no hints). */
export function publicPayload(type: QuestionType, payload: unknown) {
  if (type === "CONCEPTUAL") return {}; // key points are marking criteria - hidden until feedback
  if (type === "ASSERTION_REASON") return { ...(payload as object), options: AR_OPTIONS };
  return payload ?? {};
}
